import assert from "node:assert/strict"
import { describe, it } from "node:test"
import { getMobileMessages, maxClipLengthLabel, t } from "./index.js"

describe("mobile-i18n", () => {
  it("interpolates variables", () => {
    const m = getMobileMessages("en-CA")
    assert.equal(t(m, "capture.maxDuration", { minutes: 5 }), "Max clip length: 5 min")
    assert.equal(
      maxClipLengthLabel(m, { maxDurationSeconds: 0, hasSubscription: false }),
      "Max clip length: 0 - No subscription yet",
    )
    assert.equal(maxClipLengthLabel(m, { maxDurationSeconds: 300, hasSubscription: true }), "Max clip length: 5 min")
  })

  it("falls back to en-CA", () => {
    const m = getMobileMessages("xx")
    assert.equal(m.capture.title, "Capture")
  })

  it("has calendar event-link strings in every locale", () => {
    for (const locale of ["en-CA", "es-ES", "sv-SE"] as const) {
      const m = getMobileMessages(locale)
      assert.ok(m.metadata.eventLink.label.length > 0)
      assert.ok(m.metadata.eventLink.notLinked.length > 0)
      assert.ok(m.metadata.eventLink.emptyTeam.length > 0)
      assert.ok(m.metadata.eventLink.selectedEvent.length > 0)
      assert.ok(m.metadata.eventLink.signInRequired.length > 0)
      assert.ok(m.metadata.arenaSearchPlaceholder.length > 0)
      assert.ok(m.metadata.useNearestVenue.length > 0)
      assert.ok(m.metadata.locationUnavailable.length > 0)
      assert.ok(m.metadata.locationServicesOff.length > 0)
      assert.ok(m.home.title.length > 0)
      assert.ok(m.home.uploadFromEvent.includes("{kind}"))
      assert.ok(m.notifications.dismiss.length > 0)
      assert.ok(m.notifications.dismissAll.length > 0)
      assert.ok(m.notifications.loadFailed.length > 0)
      assert.ok(m.capture.signInRequiredBody.length > 0)
      assert.ok(m.account.signInHint.length > 0)
      assert.ok(m.auth.signInWithGoogle.length > 0)
      assert.ok(m.auth.signInWithMicrosoft.length > 0)
      assert.ok(m.auth.signInWithApple.length > 0)
      assert.ok(m.auth.appleUnavailable.length > 0)
      assert.ok(m.auth.googleLoading.length > 0)
      assert.ok(m.auth.microsoftRedirectUnregistered.includes("{uri}"))
      assert.ok(m.auth.googleNativeClientMisconfigured.includes("{platform}"))
      assert.ok(m.account.signInWithGoogle.length > 0)
      assert.ok(m.account.signInWithApple.length > 0)
      assert.ok(m.capture.maxDurationNoSubscription.length > 0)
      assert.ok(m.capture.subscriptionRequired.length > 0)
      assert.ok(m.capture.subscribeOnWebsite.length > 0)
      assert.ok(m.account.subscriptionNeeded.length > 0)
      assert.ok(m.account.quotaPools.includes("{count}"))
      assert.ok(m.account.guardianManaged.length > 0)
      assert.ok(m.diagnostics.title.length > 0)
      assert.ok(m.home.title.length > 0)
      assert.ok(m.home.emptyTitle.length > 0)
      assert.ok(m.home.uploadFromEvent.includes("{kind}"))
      assert.ok(m.home.uploadFromEvent.includes("{title}"))
      assert.ok(m.home.backToHome.length > 0)
      assert.ok(m.home.suggestedActionsTitle.length > 0)
      assert.ok(m.home.upcomingTitle.length > 0)
      assert.ok(m.home.showMore.includes("{count}"))
      assert.ok(m.home.showLess.length > 0)
      assert.ok(m.home.noPosition.length > 0)
      assert.ok(m.home.viewSchedule.length > 0)
      assert.ok(m.home.subscriptionActive.length > 0)
      assert.ok(m.home.expandCard.length > 0)
      assert.ok(m.home.collapseCard.length > 0)
      assert.ok(m.home.shareInvite.length > 0)
      assert.ok(m.home.shareInviteTitle.length > 0)
      assert.ok(m.home.shareInviteBody.length > 0)
      assert.ok(m.home.shareInviteClose.length > 0)
      assert.ok(m.home.peerInviteLabel.length > 0)
      assert.ok(m.home.referralCodeLabel.length > 0)
      assert.ok(m.home.referralActive.length > 0)
      assert.ok(m.home.referralInactive.length > 0)
      assert.ok(m.home.teamCardLabel.length > 0)
      assert.ok(m.home.shareInviteLoadFailed.length > 0)
      assert.ok(m.home.openMorphosWebsite.length > 0)
      assert.ok(m.home.openSubscribeWebsite.length > 0)
      assert.ok(m.schedule.title.length > 0)
      assert.ok(m.schedule.upcoming.length > 0)
      assert.ok(m.schedule.thisWeek.length > 0)
      assert.ok(m.schedule.showEarlier.length > 0)
      assert.ok(m.schedule.empty.length > 0)
      assert.ok(m.schedule.emptyTeam.length > 0)
      assert.ok(m.schedule.loadFailed.length > 0)
      assert.ok(m.diagnostics.stillStarting.length > 0)
      assert.ok(m.diagnostics.phases.jsStarted.length > 0)
      assert.ok(m.diagnostics.phases.sessionReady.length > 0)
      assert.ok(m.errors.sessionExpired.length > 0)
      assert.ok(m.errors.transcode_failed.length > 0)
      assert.ok(m.capture.processingProgress.includes("{percent}"))
      assert.ok(m.account.profileUnavailable.length > 0)
    }
  })
})
